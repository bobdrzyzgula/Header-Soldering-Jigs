#!/usr/bin/env python3
"""Extract header-hole positions and top-side component outlines from an
EasyEDA-exported board STEP file and write them as an OpenSCAD data file.

Written by Claude at Bob's direction.

Usage:
    pip install --break-system-packages "cadquery-ocp<7.9"   # OCCT 7.8 bindings
    python3 extract_step_to_scad.py 3D_RP350B.step rp2350b_data.scad

Assumptions (true for 3D_RP350B.step): board bottom at z=0, top at z=1.6,
header holes are 1.1 mm plated holes, mounting holes are 2.26 mm, and the
1x4 middle header sits at x = 31.09 mm. Change HEADER_D / MOUNT_D / MID_X for
another board.
"""
import sys
from OCP.STEPCAFControl import STEPCAFControl_Reader
from OCP.TDocStd import TDocStd_Document
from OCP.TCollection import TCollection_ExtendedString
from OCP.XCAFDoc import XCAFDoc_DocumentTool
from OCP.TDF import TDF_LabelSequence, TDF_Label
from OCP.TDataStd import TDataStd_Name
from OCP.TopLoc import TopLoc_Location
from OCP.Bnd import Bnd_Box
from OCP.BRepBndLib import BRepBndLib
from OCP.BRepAdaptor import BRepAdaptor_Surface
from OCP.GeomAbs import GeomAbs_Cylinder
from OCP.TopExp import TopExp_Explorer
from OCP.TopAbs import TopAbs_FACE
from OCP.TopoDS import TopoDS
from OCP.BRepMesh import BRepMesh_IncrementalMesh
from OCP.BRep import BRep_Tool

HEADER_D, MOUNT_D, MID_X, BOARD_TOP = 1.1, 2.26, 31.09, 1.6

step, out_path = sys.argv[1], sys.argv[2]
doc = TDocStd_Document(TCollection_ExtendedString("doc"))
rd = STEPCAFControl_Reader(); rd.SetNameMode(True)
rd.ReadFile(step); rd.Transfer(doc)
st = XCAFDoc_DocumentTool.ShapeTool_s(doc.Main())

def name(l):
    n = TDataStd_Name()
    return n.Get().ToExtString() if l.FindAttribute(TDataStd_Name.GetID_s(), n) else "?"

shapes = []
def walk(l, loc):
    if st.IsReference_s(l):
        ref = TDF_Label(); st.GetReferredShape_s(l, ref)
        loc = loc * st.GetLocation_s(l); nm = name(ref); l = ref
    else:
        nm = name(l)
    if st.IsAssembly_s(l):
        ch = TDF_LabelSequence(); st.GetComponents_s(l, ch)
        for i in range(1, ch.Length() + 1): walk(ch.Value(i), loc)
        return
    s = st.GetShape_s(l).Moved(loc)
    b = Bnd_Box(); BRepBndLib.Add_s(s, b, False)
    if not b.IsVoid(): shapes.append((nm, s, b.Get()))

free = TDF_LabelSequence(); st.GetFreeShapes(free)
for i in range(1, free.Length() + 1): walk(free.Value(i), TopLoc_Location())

board_nm, board, bb = [t for t in shapes if "Board" in t[0]][0]

# plated holes = vertical cylindrical faces of the board solid
holes = set()
e = TopExp_Explorer(board, TopAbs_FACE)
while e.More():
    a = BRepAdaptor_Surface(TopoDS.Face_s(e.Current()))
    if a.GetType() == GeomAbs_Cylinder:
        c = a.Cylinder()
        if abs(c.Axis().Direction().Z()) > 0.99:
            p = c.Location(); holes.add((round(p.X(), 3), round(p.Y(), 3), round(2 * c.Radius(), 3)))
    e.Next()
pins = [(x, y) for x, y, d in holes if abs(d - HEADER_D) < 0.01]
mid = sorted([p for p in pins if abs(p[0] - MID_X) < 0.01], key=lambda p: -p[1])
outer = sorted([p for p in pins if p not in mid], key=lambda p: (-p[1], p[0]))
mounts = sorted([(x, y) for x, y, d in holes if abs(d - MOUNT_D) < 0.01])

def hull(pts):
    pts = sorted(set(pts))
    cr = lambda o, a, b: (a[0]-o[0])*(b[1]-o[1]) - (a[1]-o[1])*(b[0]-o[0])
    lo, up = [], []
    for p in pts:
        while len(lo) >= 2 and cr(lo[-2], lo[-1], p) <= 0: lo.pop()
        lo.append(p)
    for p in reversed(pts):
        while len(up) >= 2 and cr(up[-2], up[-1], p) <= 0: up.pop()
        up.append(p)
    return lo[:-1] + up[:-1]

comps = []
for nm, s, _ in shapes:
    if any(k in nm for k in ("Board", "Silk", "Track", "Stiffener")): continue
    BRepMesh_IncrementalMesh(s, 0.05)
    pts, zt = [], -9
    e = TopExp_Explorer(s, TopAbs_FACE)
    while e.More():
        loc = TopLoc_Location()
        t = BRep_Tool.Triangulation_s(TopoDS.Face_s(e.Current()), loc)
        if t is not None:
            tr = loc.Transformation()
            for i in range(1, t.NbNodes() + 1):
                p = t.Node(i).Transformed(tr)
                pts.append((round(p.X(), 2), round(p.Y(), 2))); zt = max(zt, p.Z())
        e.Next()
    if pts: comps.append((nm, zt - BOARD_TOP, hull(pts)))

fmt = lambda P: "[" + ", ".join(f"[{x:.3f},{y:.3f}]" for x, y in P) + "]"
yc = round((bb[1] + bb[4]) / 2, 3)
with open(out_path, "w") as f:
    f.write(f"""// ---- Data extracted from {step.split('/')[-1]} (board coordinates, mm; board top face at z={BOARD_TOP}) ----
// Generated by extract_step_to_scad.py
BOARD_MIN = [{bb[0]:.3f}, {bb[1]:.3f}];
BOARD_MAX = [{bb[3]:.3f}, {bb[4]:.3f}];
BOARD_YC  = {yc};          // centre line the hole pattern is symmetric about (flip axis)
OUTER_PINS = {fmt(outer)};
MID_PINS = {fmt(mid)};
MOUNT_HOLES = {fmt(mounts)};
// Top-side components: [name, height above board top, 2D convex outline]
COMPONENTS = [
""" + ",\n".join(f'  ["{n[:40]}", {h:.2f}, {fmt(H)}]' for n, h, H in comps) + "\n];\n")
print(f"{len(outer)} outer pins, {len(mid)} middle pins, {len(comps)} components -> {out_path}")
